import { getDataset } from '@/ai/dataset';
import { callerKey, checkRateLimit } from '@/ai/rate-limit';
import { isBodyTooLarge, isJsonRequest, MAX_BODY_BYTES } from '@/ai/validate';
import { evaluateWatch, sanitizeRunRequest } from '@/automations/engine';

/**
 * POST /api/automations/run
 *
 * Body:  { job: 'watch-cl' | 'watch-conversion' | 'watch-revenue' | 'watch-training',
 *          regions?: string[] }
 * Reply: { job, regions, hits: WatchHit[], checkedAt }
 *
 * Evaluates a watch against the real dataset, through the same
 * `rank_attention` the Today tab and the map use. Briefs never call this
 * route: they are composed from the `TodayPriorities` the page already has.
 *
 * Guards, in order: content type, body size, rate limit, then the job and
 * regions are whitelisted against the dataset. No model is involved, so this
 * works with or without an LLM key.
 */

export const runtime = 'nodejs';

function jsonError(message: string, status: number): Response {
  return Response.json({ error: message }, { status });
}

export async function POST(request: Request): Promise<Response> {
  if (!isJsonRequest(request.headers.get('content-type'))) {
    return jsonError('Content-Type must be application/json.', 415);
  }

  if (isBodyTooLarge(request.headers.get('content-length'))) {
    return jsonError(`Request too large. Limit is ${Math.round(MAX_BODY_BYTES / 1024)} KB.`, 413);
  }

  // Cheap, deterministic work, but still rate limited so a loop cannot hammer
  // the server on demo day.
  const limit = checkRateLimit(callerKey(request), { limit: 60, windowMs: 60_000 });
  if (!limit.allowed) {
    return Response.json(
      { error: `Too many checks in a short time. Try again in ${limit.retryAfterSeconds}s.` },
      { status: 429, headers: { 'Retry-After': String(limit.retryAfterSeconds) } },
    );
  }

  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return jsonError('Invalid JSON body.', 400);
  }

  let response: Response;
  try {
    const dataset = getDataset();
    const validRegions = [...new Set(dataset.practices.map((practice) => practice.region))];
    const run = sanitizeRunRequest(body, validRegions);
    if (!run) {
      return jsonError('Unknown automation or scope.', 400);
    }
    const hits = evaluateWatch(dataset, run.job, run.regions);
    response = Response.json(
      { job: run.job, regions: run.regions, hits, checkedAt: Date.now() },
      { headers: { 'Cache-Control': 'no-store', 'X-RateLimit-Remaining': String(limit.remaining) } },
    );
  } catch {
    // The dataset is generated by `npm run seed`; a failure here means the
    // CSVs are missing, which the operator fixes, not the caller.
    response = jsonError('The data layer is unavailable. Run the seed and try again.', 500);
  }

  return response;
}
